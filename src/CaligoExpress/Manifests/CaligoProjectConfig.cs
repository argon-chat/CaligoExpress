namespace CaligoExpress.Manifests;

using System.Text.Json.Serialization;

/// <summary>
/// The single source of truth for a deployment, edited as <c>caligo.json</c>. The `caligo init` command
/// derives everything else from it: the signed bootstrap <see cref="ConfigManifest"/> served to clients,
/// and the <see cref="InstallerRuntimeConfig"/> embedded in the installer. Change it once, re-run init.
/// </summary>
public sealed class CaligoProjectConfig
{
    [JsonPropertyName("appName")] public string AppName { get; set; } = "App";

    /// <summary>App slug on a multi-app worker: manifests/artifacts live under <c>apps/&lt;appId&gt;/</c>
    /// and the control plane is addressed at <c>{workerUrl}/apps/&lt;appId&gt;</c>. Leave null/empty for the
    /// worker's default app (Argon), which keeps the legacy root layout. Lowercase letters/digits/dashes.</summary>
    [JsonPropertyName("appId")] public string? AppId { get; set; }
    [JsonPropertyName("bootstrapperFileName")] public string BootstrapperFileName { get; set; } = "Installer.exe";
    [JsonPropertyName("defaultChannel")] public string DefaultChannel { get; set; } = "live";
    [JsonPropertyName("channels")] public List<string> Channels { get; set; } = ["live", "beta", "canary"];

    /// <summary>Hard-coded hosts the installer races to fetch the signed config before mirrors are known.</summary>
    [JsonPropertyName("seedHosts")] public List<string> SeedHosts { get; set; } = [];

    [JsonPropertyName("scheme")] public string Scheme { get; set; } = "https";
    [JsonPropertyName("minBootstrapper")] public string MinBootstrapper { get; set; } = "1.0.0";

    [JsonPropertyName("keyId")] public string KeyId { get; set; } = "k1";

    /// <summary>Base64 Ed25519 public key. Populated by `init --keygen`.</summary>
    [JsonPropertyName("publicKey")] public string PublicKey { get; set; } = "";

    [JsonPropertyName("mirrors")] public List<MirrorEntry> Mirrors { get; set; } = [];

    /// <summary>Default launch spec for releases (the publisher can override per release).</summary>
    [JsonPropertyName("launch")] public LaunchSpec? Launch { get; set; }

    /// <summary>Control-plane worker base URL, used by the publish scripts (e.g. https://caligo-worker.example.com).</summary>
    [JsonPropertyName("workerUrl")] public string WorkerUrl { get; set; } = "";
}

/// <summary>
/// The slice of configuration the installer needs at runtime, generated by `init` and embedded in the
/// installer build: where to fetch config from, which keys to trust, its own file name, default channel.
/// </summary>
public sealed record InstallerRuntimeConfig(
    [property: JsonPropertyName("seedHosts")] List<string> SeedHosts,
    [property: JsonPropertyName("pinnedKeys")] Dictionary<string, string> PinnedKeys,
    [property: JsonPropertyName("bootstrapperFileName")] string BootstrapperFileName,
    [property: JsonPropertyName("defaultChannel")] string DefaultChannel,
    [property: JsonPropertyName("scheme")] string Scheme,
    // Null (omitted) for the default app — existing installers' embedded configs stay valid.
    [property: JsonPropertyName("appId")] string? AppId = null);
